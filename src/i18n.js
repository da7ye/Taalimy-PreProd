/** Simple interpolation helper: t("Hello {{name}}", { name: "Ali" }) → "Hello Ali" */
export function interpolate(str, vars = {}) {
  if (!str) return "";
  return str.replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k] ?? `{{${k}}}`);
}